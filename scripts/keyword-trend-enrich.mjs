import fs from 'node:fs';
import path from 'node:path';

const roots = fs.readdirSync('C:\\').map((name) => path.join('C:\\', name, 'project'));
const root = roots.find((candidate) => fs.existsSync(path.join(candidate, 'package.json')));
if (!root) throw new Error('EzyJobs project not found');

const file = path.join(root, 'public', 'keyword-intelligence.json');
const snapshot = JSON.parse(fs.readFileSync(file, 'utf8'));

const parseJson = (text) => {
  const start = text.search(/[{[]/);
  if (start < 0) throw new Error('No JSON payload');
  return JSON.parse(text.slice(start));
};

async function getTrendBatch(rows) {
  const req = {
    comparisonItem: rows.map((row) => ({ keyword: row.keyword, geo: row.geo, time: 'today 12-m' })),
    category: 0,
    property: '',
  };
  const exploreUrl = new URL('https://trends.google.com/trends/api/explore');
  exploreUrl.searchParams.set('hl', 'en-US');
  exploreUrl.searchParams.set('tz', '-60');
  exploreUrl.searchParams.set('req', JSON.stringify(req));

  const exploreResponse = await fetch(exploreUrl, {
    headers: { 'User-Agent': 'EzyJobs/1.0 keyword-intelligence', Accept: 'application/json' },
    signal: AbortSignal.timeout(20000),
  });
  if (!exploreResponse.ok) throw new Error('Explore HTTP ' + exploreResponse.status);
  const explore = parseJson(await exploreResponse.text());

  const widget = (explore.widgets || []).find((item) => item.id === 'TIMESERIES') ||
    (explore.widgets || []).find((item) => /interest over time/i.test(item.title || ''));
  if (!widget) throw new Error('TIMESERIES widget not returned');

  const widgetUrl = new URL('https://trends.google.com/trends/api/widgetdata/multiline');
  widgetUrl.searchParams.set('hl', 'en-US');
  widgetUrl.searchParams.set('tz', '-60');
  widgetUrl.searchParams.set('req', JSON.stringify(widget.request));
  widgetUrl.searchParams.set('token', widget.token);

  const widgetResponse = await fetch(widgetUrl, {
    headers: { 'User-Agent': 'EzyJobs/1.0 keyword-intelligence', Accept: 'application/json' },
    signal: AbortSignal.timeout(20000),
  });
  if (!widgetResponse.ok) throw new Error('Widget HTTP ' + widgetResponse.status);
  const widgetData = parseJson(await widgetResponse.text());
  const timeline = widgetData?.default?.timelineData || [];

  const series = rows.map((row, index) => {
    const values = timeline
      .map((point) => Number(point?.value?.[index] ?? 0))
      .filter((value) => Number.isFinite(value));
    const window = values.slice(-12);
    const average = window.length ? window.reduce((sum, value) => sum + value, 0) / window.length : 0;
    return { keyword: row.keyword, average };
  });
  const max = Math.max(1, ...series.map((item) => item.average));
  return new Map(series.map((item) => [item.keyword, Math.round((item.average / max) * 100)]));
}

const grouped = new Map();
for (const row of snapshot.keywords) {
  const key = row.geo + '|' + row.locale;
  const list = grouped.get(key) || [];
  list.push(row);
  grouped.set(key, list);
}

const errors = [...(snapshot.errors || [])];
for (const rows of grouped.values()) {
  for (let start = 0; start < rows.length; start += 5) {
    const batch = rows.slice(start, start + 5);
    try {
      const scores = await getTrendBatch(batch);
      for (const row of batch) {
        row.trendScore = scores.get(row.keyword) ?? 0;
        row.demandScore = Math.round(
          row.trendScore * 0.7 +
          Math.min(100, row.suggestionCount * 10) * 0.2 +
          Math.min(100, row.jobMatches * 10) * 0.1,
        );
        row.demandSignals = [...new Set([...row.demandSignals, 'google_trends_12m'])];
      }
    } catch (error) {
      errors.push({ kind: 'trends-explore', geo: batch[0]?.geo, error: String(error) });
    }
  }
}

snapshot.keywords.sort((a, b) => b.demandScore - a.demandScore || b.trendScore - a.trendScore);
snapshot.errors = errors;

fs.writeFileSync(file, JSON.stringify(snapshot, null, 2), 'utf8');
fs.writeFileSync(
  path.join(root, 'src', 'data', 'keywordIntelligence.ts'),
  "import type { KeywordDemandSnapshot } from '../types';\n\n" +
  '// Generated by keyword intelligence scripts — do not edit by hand.\n' +
  'export const keywordIntelligence = ' + JSON.stringify(snapshot, null, 2) + ' as KeywordDemandSnapshot;\n',
  'utf8',
);

console.log('Trend enrichment complete. Top: ' + snapshot.keywords.slice(0, 10).map((row) => row.keyword + ' [' + row.demandScore + ' / trend ' + (row.trendScore ?? 0) + ']').join(' | '));
if (errors.length) console.warn(JSON.stringify({ errors }, null, 2));
